// ---------------------------------------------------------------------------
// Containerfile generation
// ---------------------------------------------------------------------------
/**
 * Turn a scored machine into a Containerfile and the assumptions behind it.
 *
 * The honest limit, stated first because it decides the whole design: this
 * agent never executes anything inside the guest, so unlike App2Container it
 * CANNOT extract the application's files. It knows what runtime is running and
 * roughly how it was invoked, and nothing else about the artefact.
 *
 * So what is generated is a SCAFFOLD, not a ready-to-build image: correct in
 * structure, hardened by default, with every unknown marked as an explicit
 * assumption that a human confirms. That is worth having — it is most of the
 * boilerplate and all of the hardening — and pretending otherwise would produce
 * a file that builds into something wrong, which is worse than a file that
 * builds into nothing.
 *
 * Hardening that is NOT optional in what comes out:
 *   - a UBI base, because the target is OpenShift and the customer is buying
 *     a supported chain
 *   - no systemd, no sshd, no syslog — a container runs one process
 *   - an explicit non-root USER, because OpenShift's default SCC assigns a
 *     random uid and an image that assumes root will not start
 *   - a health endpoint wired to a probe, since "the pod is Running" is not
 *     "the application is up"
 *
 * Everything here is pure.
 */

import { RUNTIMES } from "./containerization-readiness.js";

/**
 * The port each runtime conventionally listens on.
 *
 * ASSUMED, never read. Listening ports need a command inside the guest, which
 * this agent does not run, so every one of these leaves an assumption behind
 * that the operator has to confirm. A wrong port produces a pod that passes
 * its build, starts, and never serves anything — the most expensive kind of
 * wrong, because it looks like success until cutover.
 */
export const CONVENTIONAL_PORT = Object.freeze({
  tomcat: 8080, jboss: 8080, weblogic: 7001, websphere: 9080,
  springboot: 8080, java: 8080, dotnet: 8080, nodejs: 3000,
  python: 8000, php: 8080, ruby: 3000, nginx: 8080, httpd: 8080,
});

/** Runtimes with no community base image we can honestly propose. */
export const NO_BASE_IMAGE = Object.freeze({
  weblogic: "Oracle WebLogic images are licensed and distributed by Oracle. There is no UBI equivalent to propose, and generating one would be a licensing problem rather than a technical one.",
  websphere: "IBM WebSphere images come from IBM's registry under IBM's entitlement. Use the Liberty migration path with IBM's own tooling instead.",
});

const HEADER = (ctx) => [
  "# ---------------------------------------------------------------------------",
  "# Generated by TCS Agentic AI — Containerization Agent",
  `# Source machine : ${ctx.machine}${ctx.vmId ? ` (${ctx.vmId})` : ""}`,
  `# Detected runtime: ${ctx.runtimeLabel}`,
  `# Evidence        : ${ctx.evidence || "not recorded"}`,
  "#",
  "# THIS IS A SCAFFOLD. The agent reads what is RUNNING on a machine; it never",
  "# executes anything inside the guest, so it has not seen your application's",
  "# files. Every line marked CONFIRM is an assumption, not a finding.",
  "# ---------------------------------------------------------------------------",
  "",
].join("\n");

const FOOTER = (port) => [
  "",
  "# OpenShift assigns a random uid from the namespace's range and ignores USER",
  "# when the SCC says so, so the paths the app writes to must be group-writable",
  "# by root(0). An image that only works as its own uid starts and then fails",
  "# on its first write, which reads as an application bug for about a day.",
  "USER 1001",
  "",
  `EXPOSE ${port}`,
  "",
].join("\n");

/** Per-family body. Kept declarative so a new runtime is a table entry. */
function body(runtimeId, port) {
  switch (runtimeId) {
    case "tomcat":
      return [
        "# CONFIRM: the war this machine serves, and where it lives in your build",
        "# output. The agent saw Tomcat running; it did not read the webapps",
        "# directory.",
        "COPY --chown=1001:0 target/ROOT.war /deployments/ROOT.war",
        "",
        "# CONFIRM: JVM sizing. The heap is NOT the VM's memory — a container gets",
        "# a limit, and a JVM that sizes itself from the host will be OOM-killed.",
        'ENV JAVA_OPTS_APPEND="-XX:MaxRAMPercentage=75 -XX:+UseContainerSupport"',
      ].join("\n");
    case "jboss":
      return [
        "# CONFIRM: the deployment artefact and any standalone.xml customisation.",
        "# Configuration that lives in the server's own config file has to move to",
        "# a ConfigMap or an environment variable — it will not come across on its own.",
        "COPY --chown=1001:0 target/ROOT.war /deployments/ROOT.war",
        "",
        'ENV JAVA_OPTS_APPEND="-XX:MaxRAMPercentage=75 -XX:+UseContainerSupport"',
      ].join("\n");
    case "springboot":
    case "java":
      return [
        "# CONFIRM: the executable jar this machine runs.",
        "COPY --chown=1001:0 target/application.jar /deployments/application.jar",
        "",
        'ENV JAVA_OPTS_APPEND="-XX:MaxRAMPercentage=75 -XX:+UseContainerSupport"',
        `ENV SERVER_PORT=${port}`,
      ].join("\n");
    case "dotnet":
      return [
        "# CONFIRM: the publish output directory.",
        "COPY --chown=1001:0 bin/Release/publish/ /opt/app-root/app/",
        "",
        `ENV ASPNETCORE_URLS=http://*:${port}`,
        'ENTRYPOINT ["dotnet", "/opt/app-root/app/YourApp.dll"]   # CONFIRM: the assembly name',
      ].join("\n");
    case "nodejs":
      return [
        "COPY --chown=1001:0 package*.json ./",
        "RUN npm ci --omit=dev",
        "COPY --chown=1001:0 . .",
        "",
        `ENV PORT=${port}`,
        'CMD ["node", "server.js"]   # CONFIRM: the entrypoint this machine actually runs',
      ].join("\n");
    case "python":
      return [
        "COPY --chown=1001:0 requirements.txt .",
        "RUN pip install --no-cache-dir -r requirements.txt",
        "COPY --chown=1001:0 . .",
        "",
        `# CONFIRM: the WSGI/ASGI callable. Gunicorn is assumed from the process list.`,
        `CMD ["gunicorn", "--bind", "0.0.0.0:${port}", "app:application"]`,
      ].join("\n");
    case "php":
      return [
        "COPY --chown=1001:0 . /opt/app-root/src",
        "",
        "# CONFIRM: php.ini settings this machine relies on. Anything set on the",
        "# server rather than in the repo does not come across.",
      ].join("\n");
    case "ruby":
      return [
        "COPY --chown=1001:0 Gemfile Gemfile.lock ./",
        "RUN bundle install --without development test",
        "COPY --chown=1001:0 . .",
        "",
        `CMD ["bundle", "exec", "puma", "-p", "${port}"]`,
      ].join("\n");
    case "nginx":
      return [
        "# CONFIRM: the site config and the document root. An nginx in front of an",
        "# application becomes a Route on the target, so check this machine is",
        "# serving content rather than proxying — if it proxies, delete this image",
        "# and put the rule in the Route instead.",
        "COPY --chown=1001:0 nginx.conf /etc/nginx/nginx.conf",
        "COPY --chown=1001:0 public/ /opt/app-root/src/",
      ].join("\n");
    case "httpd":
      return [
        "# CONFIRM: the vhost config and document root.",
        "COPY --chown=1001:0 httpd.conf /etc/httpd/conf/httpd.conf",
        "COPY --chown=1001:0 public/ /var/www/html/",
      ].join("\n");
    default:
      return [
        "# CONFIRM: everything below. No recognised runtime — this is a skeleton.",
        "COPY --chown=1001:0 . /opt/app-root/src",
        'CMD ["/opt/app-root/src/start.sh"]',
      ].join("\n");
  }
}

/**
 * Build the Containerfile for one detected runtime.
 *
 * @returns {{ok:boolean, reason?:string, containerfile?:string, port?:number, base?:string}}
 */
export function containerfileFor(runtime, ctx = {}) {
  if (!runtime) return { ok: false, reason: "No application runtime was detected, so there is nothing to base an image on." };
  if (NO_BASE_IMAGE[runtime.id]) return { ok: false, reason: NO_BASE_IMAGE[runtime.id] };

  const base = runtime.base || RUNTIMES.find((r) => r.id === runtime.id)?.base;
  if (!base) return { ok: false, reason: `No base image is defined for ${runtime.label}.` };

  const port = ctx.port || CONVENTIONAL_PORT[runtime.id] || 8080;
  const containerfile = [
    HEADER({ ...ctx, runtimeLabel: runtime.label, evidence: runtime.evidence }),
    `FROM ${base}:latest   # CONFIRM: pin to a digest before any pipeline uses this`,
    "",
    "WORKDIR /opt/app-root/src",
    "",
    body(runtime.id, port),
    FOOTER(port),
  ].join("\n");

  return { ok: true, containerfile, port, base };
}
